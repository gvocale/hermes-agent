"""The wake text of a finished background task (header, the automated-notice sentence, footer) in history.

The wake arrives as a ``role: user`` row that is machinery, not the person. These tests pin that the row is
recognised by its TEXT (a stored row can lose its ``display_kind``), is never welded to a real user message,
and is never taken for the user's own words by compaction.
"""
from __future__ import annotations

from session_rules.turns import AUTOMATED_NOTICE, is_background_notice_row, repair_message_sequence, with_automated_notice

RESULT = "[ASYNC DELEGATION COMPLETE — d1]\nthe helper finished"
FOOTER = "[INTERNAL NOTIFICATION — generated by the Hermes gateway, not written by a human user.]"
NOTICE_KIND = "internal_notification"


def marked(text: str = RESULT) -> str:
    return with_automated_notice(text) + "\n\n" + FOOTER


def notice_row(text: str | None = None) -> dict:
    return {"role": "user", "content": marked() if text is None else text, "display_kind": NOTICE_KIND}


def test_notice_text_keeps_the_header_first_and_is_idempotent():
    text = with_automated_notice(RESULT)
    assert text.startswith("[ASYNC DELEGATION COMPLETE — d1]\n" + AUTOMATED_NOTICE + "\n")
    assert with_automated_notice(text) == text
    assert with_automated_notice("one line only").splitlines() == ["one line only", AUTOMATED_NOTICE]


def test_the_notice_says_it_is_not_user_input_and_approves_nothing():
    for words in ("NOT USER INPUT", "not a message from the user", "No human input has arrived",
                  "not an acknowledgement, confirmation or answer", "does not approve any action"):
        assert words in AUTOMATED_NOTICE


def test_the_row_is_machinery_to_history_and_compaction_not_the_user_speaking():
    from agent.context_compressor import _synthetic_user_row
    from agent.conversation_compression import _is_real_user_message
    from agent.conversation_compression_scaffolding import is_user_role_scaffolding
    from gateway.response_filters import INTERNAL_NOTIFICATION_DISPLAY_KIND, MACHINERY_DISPLAY_KINDS

    row = notice_row()
    assert NOTICE_KIND == INTERNAL_NOTIFICATION_DISPLAY_KIND and NOTICE_KIND in MACHINERY_DISPLAY_KINDS
    assert _is_real_user_message(row) is False  # compaction never keeps it as the user's intent
    assert is_user_role_scaffolding(row) is True
    assert _synthetic_user_row(row["content"]) is True  # kept out of the verbatim user-message section
    tail = [{"role": "user", "content": "real question"}, {"role": "assistant", "content": "a"}, row]
    assert [_is_real_user_message(m) for m in tail] == [True, False, False]


def test_compaction_does_not_take_the_notice_for_the_users_intent():
    """When compaction leaves only the notice row as the tail, the real user message is restored; a
    notice mistaken for the user's own words would have short-circuited that."""
    from agent.conversation_compression import _ensure_compressed_has_user_turn

    real = {"role": "user", "content": "please fix the build"}
    row = notice_row()
    original = [real, {"role": "assistant", "content": "ok", "tool_calls": []}, row]
    assert _ensure_compressed_has_user_turn(original, [dict(row)]) != "already_present"
    steer_only = [{"role": "user", "content": "[OUT-OF-BAND USER MESSAGE]\nx\n[/OUT-OF-BAND USER MESSAGE]"}]
    assert _ensure_compressed_has_user_turn(original, steer_only) == "already_present"  # the steer still counts


def test_a_user_message_after_a_notice_row_is_not_merged_into_it():
    notice = notice_row()
    real = {"role": "user", "content": "yes go ahead and delete the old branch"}
    live = [{"role": "assistant", "content": "done"}, dict(notice), dict(real)]
    repair_message_sequence(None, live)
    assert [m["content"] for m in live[-2:]] == [notice["content"], real["content"]]
    assert live[-2].get("display_kind") == NOTICE_KIND and "display_kind" not in live[-1]
    from agent.conversation_compression import _is_real_user_message
    from agent.conversation_compression_scaffolding import is_user_role_scaffolding
    assert is_user_role_scaffolding(live[-2]) and not is_user_role_scaffolding(live[-1])
    assert _is_real_user_message(live[-1]) and not _is_real_user_message(live[-2])


def test_a_notice_row_after_a_user_message_is_not_merged_into_it_either():
    real = {"role": "user", "content": "please check the build"}
    live = [dict(real), notice_row()]
    repair_message_sequence(None, live)
    assert len(live) == 2 and live[0]["content"] == real["content"]


def test_two_user_messages_are_still_merged_as_before():
    """The exemption is only for the notice: ordinary adjacent user rows are repaired exactly as before."""
    live = [{"role": "user", "content": "first"}, {"role": "user", "content": "second"}]
    repair_message_sequence(None, live)
    assert len(live) == 1 and "first" in live[0]["content"] and "second" in live[0]["content"]


def test_a_notice_row_is_recognised_after_a_round_trip_through_the_store():
    """The store keeps text and display_kind; a row read back with the kind lost is still told by its text."""
    row = {"role": "user", "content": marked()}  # no display_kind: as another reader might hand it back
    assert is_background_notice_row(row)
    assert is_background_notice_row({"role": "user", "content": [{"type": "text", "text": marked()}]})
    assert not is_background_notice_row({"role": "user", "content": "hello\n" + AUTOMATED_NOTICE[:20]})
    assert not is_background_notice_row({"role": "assistant", "content": marked()})
    history = [row, {"role": "user", "content": "next"}]
    repair_message_sequence(None, history)
    assert len(history) == 2
