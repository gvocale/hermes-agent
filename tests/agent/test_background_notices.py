"""A background result handed to a RUNNING turn (``agent.background_notices``).

The turns here run the real agent loop (``AIAgent.run_conversation``, real tool dispatch, real
``prepare_iteration``); only the model is scripted (``_interruptible_api_call`` is replaced), so each
test says exactly what the model was shown at every step.
"""
from __future__ import annotations

from types import SimpleNamespace
from unittest.mock import MagicMock, patch

from agent.background_notices import (
    AUTOMATED_NOTICE, NOTICE_DISPLAY_KIND, Notice, close_turn, deliver_pending_notices,
    notice_user_row, post_notice, reopen_turn, with_automated_notice,
)
from agent.prompt_builder import STEER_MARKER_OPEN
from tools.registry import registry

PROBE_TOOL = "background_notice_probe"
RESULT = "[ASYNC DELEGATION COMPLETE — d1]\nthe helper finished"
FOOTER = "[INTERNAL NOTIFICATION — generated by the Hermes gateway, not written by a human user.]"


def _probe_handler(args, **_kwargs):
    return "probe ok"


registry.register(
    name=PROBE_TOOL, toolset="utility", handler=_probe_handler, override=True,
    schema={"name": PROBE_TOOL, "description": "probe tool for the background notice tests",
            "parameters": {"type": "object", "properties": {}, "required": []}})


def marked(text: str = RESULT) -> str:
    return f"{with_automated_notice(text)}\n\n{FOOTER}"


def loop_agent():
    """A real ``AIAgent`` with a scripted model (set ``agent._interruptible_api_call``)."""
    from run_agent import AIAgent
    schema = {"type": "function", "function": {
        "name": PROBE_TOOL, "description": "probe", "parameters": {"type": "object", "properties": {}}}}
    with (patch("model_tools.get_tool_definitions", return_value=[schema]),
          patch("model_tools.check_toolset_requirements", return_value={}),
          patch("agent.process_bootstrap.OpenAI")):
        agent = AIAgent(api_key="test-key-1234567890", base_url="https://openrouter.ai/api/v1",
                        quiet_mode=True, skip_context_files=True, skip_memory=True)
    agent.client = MagicMock()
    agent._disable_streaming = True
    agent._cached_system_prompt = "You are helpful."
    agent._use_prompt_caching = False
    agent.tool_delay = 0
    agent.compression_enabled = False
    agent.save_trajectories = False
    return agent


def run_turn(agent, script, user="start"):
    """Run one turn. ``script(call_number, payload_messages)`` runs during each model call and returns
    ``"tool"`` (the model asks for the probe tool) or ``"final"``. Returns (result, payloads)."""
    from tests.agent.test_run_agent import _mock_response
    payloads: list = []

    def model_call(api_kwargs):
        payloads.append([dict(m) for m in api_kwargs["messages"]])
        if script(len(payloads), payloads[-1]) == "tool":
            call = SimpleNamespace(id=f"call_{len(payloads)}", type="function",
                                   function=SimpleNamespace(name=PROBE_TOOL, arguments="{}"))
            return _mock_response(content=None, finish_reason="tool_calls", tool_calls=[call])
        return _mock_response(content="done", finish_reason="stop")

    agent._interruptible_api_call = model_call
    with (patch.object(agent, "_flush_messages_to_session_db"), patch.object(agent, "_persist_session"),
          patch.object(agent, "_save_trajectory"), patch.object(agent, "_cleanup_task_resources")):
        result = agent.run_conversation(user)
    return result, payloads


def copies(payloads, text) -> int:
    """How many rows over all model calls carry *text* (each call re-sends history, so count the
    LAST call's rows only: that is what the model finally saw)."""
    return sum(str(m.get("content")).count(text) for m in payloads[-1])


def test_notice_posted_during_a_model_call_is_read_at_the_next_step_boundary():
    agent = loop_agent()
    reopen_turn(agent)

    def script(n, _messages):
        if n == 1:
            assert post_notice(agent, Notice(marked()))  # the result arrives while the model is working
            return "tool"
        return "final"

    result, payloads = run_turn(agent, script)
    assert len(payloads) == 2 and result["completed"] is True
    assert RESULT.splitlines()[1] not in str(payloads[0])  # not before the step boundary
    second = payloads[1]
    assert [m["role"] for m in second[-3:]] == ["assistant", "tool", "user"]  # after the tool batch
    row = second[-1]
    # the request carries plain role/content; the stored row keeps its machine type
    stored = [m for m in result["messages"] if m.get("display_kind") == NOTICE_DISPLAY_KIND]
    assert len(stored) == 1 and stored[0]["content"] == row["content"] and stored[0]["role"] == "user"
    assert row["content"].startswith("[ASYNC DELEGATION COMPLETE — d1]")  # start-anchored consumers match
    assert row["content"].endswith(FOOTER)  # end-anchored consumers match
    assert AUTOMATED_NOTICE in row["content"] and "NOT USER INPUT" in row["content"]
    assert "no human input" in row["content"].lower()
    assert "not an acknowledgement, confirmation or answer" in row["content"]
    assert STEER_MARKER_OPEN not in str(second)  # never presented as the user speaking
    assert copies(payloads, "the helper finished") == 1
    assert close_turn(agent) == []  # consumed: nothing left for a new turn


def test_notice_that_arrives_during_the_final_answer_is_handed_back_unread():
    agent = loop_agent()
    reopen_turn(agent)
    notice = Notice(marked(), payload={"id": "d1"})

    def script(n, _messages):
        if n == 1:
            return "tool"
        assert post_notice(agent, notice)  # arrives while the model writes its final answer
        return "final"

    _result, payloads = run_turn(agent, script)
    assert len(payloads) == 2
    assert "the helper finished" not in str(payloads)  # no later model call: the turn never read it
    assert close_turn(agent) == [notice]  # the owner gets it back, once, with its own payload
    assert close_turn(agent) == []
    assert post_notice(agent, Notice(marked())) is False  # a closed turn takes nothing more


def test_two_results_in_one_turn_are_one_row_each_read_once():
    agent = loop_agent()
    reopen_turn(agent)

    def script(n, _messages):
        if n == 1:
            post_notice(agent, Notice(marked("[ASYNC DELEGATION COMPLETE — d1]\nfirst helper done")))
            post_notice(agent, Notice(marked("[ASYNC DELEGATION COMPLETE — d2]\nsecond helper done")))
            return "tool"
        if n == 2:
            return "tool"
        return "final"

    result, payloads = run_turn(agent, script)
    assert len(payloads) == 3
    assert copies(payloads, "first helper done") == 1 and copies(payloads, "second helper done") == 1
    notice_rows = [m for m in result["messages"] if m.get("display_kind") == NOTICE_DISPLAY_KIND]
    assert len(notice_rows) == 1  # delivered together at one boundary
    assert notice_rows[0]["content"].count(AUTOMATED_NOTICE) == 2  # each result carries its own notice
    assert close_turn(agent) == []


def test_notice_posted_before_any_tool_result_waits_for_a_boundary():
    agent = loop_agent()
    reopen_turn(agent)
    post_notice(agent, Notice(marked()))
    messages = [{"role": "user", "content": "hi"}]
    assert deliver_pending_notices(agent, messages) == 0 and len(messages) == 1  # nothing to follow
    messages.append({"role": "tool", "content": "ok", "tool_call_id": "c"})
    assert deliver_pending_notices(agent, messages) == 1
    assert messages[-1]["role"] == "user" and messages[-1]["display_kind"] == NOTICE_DISPLAY_KIND


def test_without_any_notice_the_model_sees_exactly_what_it_saw_before():
    def script(n, _messages):
        return "tool" if n == 1 else "final"

    plain_result, plain = run_turn(loop_agent(), script)
    opened = loop_agent()
    reopen_turn(opened)
    _result, with_buffer = run_turn(opened, script)
    again = loop_agent()
    post_notice(again, Notice(marked()))
    close_turn(again)  # an agent that was handed something and then closed: next turn reopens it
    reopen_turn(again)
    _result, reopened = run_turn(again, script)

    def shape(payloads):
        return [[(m["role"], m.get("content")) for m in call if m["role"] != "system"] for call in payloads]

    assert shape(plain) == shape(with_buffer) == shape(reopened)
    assert plain_result["completed"] is True


def test_a_reopened_agent_takes_notices_again():
    agent = loop_agent()
    assert close_turn(agent) == []
    assert post_notice(agent, Notice("x")) is True  # an agent with no buffer yet opens one
    assert close_turn(agent) == [Notice("x")]
    assert post_notice(agent, Notice("late")) is False
    reopen_turn(agent)
    assert post_notice(agent, Notice("next turn")) is True


def test_the_row_is_machinery_to_history_and_compaction_not_the_user_speaking():
    from agent.context_compressor import _synthetic_user_row
    from agent.conversation_compression import (
        _compressed_has_busy_steer, _is_real_user_message, _message_contains_busy_steer,
    )
    from gateway.response_filters import INTERNAL_NOTIFICATION_DISPLAY_KIND, MACHINERY_DISPLAY_KINDS
    from agent.conversation_compression_scaffolding import is_user_role_scaffolding

    row = notice_user_row(marked())
    assert NOTICE_DISPLAY_KIND == INTERNAL_NOTIFICATION_DISPLAY_KIND in MACHINERY_DISPLAY_KINDS
    assert row["role"] == "user"
    assert _is_real_user_message(row) is False  # compaction never keeps it as the user's intent
    assert is_user_role_scaffolding(row) is True
    assert _synthetic_user_row(row["content"]) is True  # kept out of the verbatim user-message section
    assert not _message_contains_busy_steer(row) and not _compressed_has_busy_steer([row])
    tail = [{"role": "user", "content": "real question"}, {"role": "assistant", "content": "a"}, row]
    assert [_is_real_user_message(m) for m in tail] == [True, False, False]


def test_notice_text_keeps_the_header_first_and_is_idempotent():
    text = with_automated_notice(RESULT)
    assert text.startswith("[ASYNC DELEGATION COMPLETE — d1]\n" + AUTOMATED_NOTICE + "\n")
    assert with_automated_notice(text) == text
    assert with_automated_notice("one line only").splitlines() == ["one line only", AUTOMATED_NOTICE]


def test_compaction_does_not_take_the_notice_for_the_users_intent():
    """When compaction leaves only the notice row as the tail, the real user message is restored; a
    notice mistaken for the user's own words would have short-circuited that."""
    from agent.conversation_compression import _ensure_compressed_has_user_turn

    real = {"role": "user", "content": "please fix the build"}
    row = notice_user_row(marked())
    original = [real, {"role": "assistant", "content": "ok", "tool_calls": []}, row]
    outcome = _ensure_compressed_has_user_turn(original, [dict(row)])
    assert outcome != "already_present"
    steer_only = [{"role": "user", "content": "[OUT-OF-BAND USER MESSAGE]\nx\n[/OUT-OF-BAND USER MESSAGE]"}]
    assert _ensure_compressed_has_user_turn(original, steer_only) == "already_present"  # the steer still counts


# -- a notice row is never welded to a real user row, and never shares a boundary with a /steer ----------


def _adjacent_users(messages) -> bool:
    return any(a["role"] == "user" and b["role"] == "user" for a, b in zip(messages, messages[1:]))


def test_a_user_message_after_a_notice_row_is_not_merged_into_it_in_the_live_list():
    from session_rules.turns import repair_message_sequence
    notice = notice_user_row(marked())
    real = {"role": "user", "content": "yes go ahead and delete the old branch"}
    live = [{"role": "assistant", "content": None, "tool_calls": [{"id": "c", "type": "function",
            "function": {"name": PROBE_TOOL, "arguments": "{}"}}]},
            {"role": "tool", "tool_call_id": "c", "content": "ok"}, dict(notice), dict(real)]
    repair_message_sequence(None, live)
    assert [m["content"] for m in live[-2:]] == [notice["content"], real["content"]]
    assert live[-2].get("display_kind") == NOTICE_DISPLAY_KIND  # the notice row keeps its type
    assert "display_kind" not in live[-1]
    from agent.conversation_compression_scaffolding import is_user_role_scaffolding
    from agent.conversation_compression import _is_real_user_message
    assert is_user_role_scaffolding(live[-2]) and not is_user_role_scaffolding(live[-1])
    assert _is_real_user_message(live[-1]) and not _is_real_user_message(live[-2])


def test_a_notice_row_after_a_user_message_is_not_merged_into_it_either():
    from session_rules.turns import repair_message_sequence
    real = {"role": "user", "content": "please check the build"}
    live = [dict(real), notice_user_row(marked())]
    repair_message_sequence(None, live)
    assert [m["content"] for m in live][0] == real["content"] and len(live) == 2


def test_a_notice_row_is_recognised_after_a_round_trip_through_the_store():
    """The store keeps text and display_kind; a row read back with the kind lost is still told by its text, and
    the rows around it stay separate."""
    from session_rules.turns import is_background_notice_row, repair_message_sequence
    row = {"role": "user", "content": marked()}  # no display_kind: as another reader might hand it back
    assert is_background_notice_row(row)
    assert is_background_notice_row({"role": "user", "content": [{"type": "text", "text": marked()}]})
    assert not is_background_notice_row({"role": "user", "content": "hello\n" + AUTOMATED_NOTICE[:20]})
    assert not is_background_notice_row({"role": "assistant", "content": marked()})
    history = [row, {"role": "user", "content": "next"}]
    repair_message_sequence(None, history)
    assert len(history) == 2


def test_a_steer_that_lands_at_the_boundary_does_not_share_a_row_with_the_notice():
    """A /steer arriving after the post-tool drain and before the iteration's own drain (modelled from the
    step callback, which runs between them). Before: one row held the steer block followed by the result."""
    agent = loop_agent()
    reopen_turn(agent)

    def on_step(iteration, _previous):
        if iteration == 2:
            agent.steer("please also look at the logs")

    agent.step_callback = on_step

    def script(n, _messages):
        if n == 1:
            assert post_notice(agent, Notice(marked()))
        return "tool" if n < 3 else "final"

    result, payloads = run_turn(agent, script)
    assert result["completed"] is True and len(payloads) == 3
    for payload in payloads:
        assert not _adjacent_users(payload), [m["role"] for m in payload]  # valid for every provider adapter
        for message in payload:
            text = str(message.get("content"))
            assert not (STEER_MARKER_OPEN in text and "the helper finished" in text), "steer and notice in one row"
    second, third = payloads[1], payloads[2]
    assert STEER_MARKER_OPEN in str(second) and "the helper finished" not in str(second)  # the steer went first
    assert copies(payloads, "the helper finished") == 1  # the notice followed at the next boundary, once
    assert [m["role"] for m in third[-2:]] == ["tool", "user"]
    assert close_turn(agent) == []


def test_a_notice_left_by_a_steer_boundary_is_handed_back_when_the_turn_ends():
    agent = loop_agent()
    reopen_turn(agent)
    agent.step_callback = lambda iteration, _previous: iteration == 2 and agent.steer("one more thing")

    def script(n, _messages):
        if n == 1:
            assert post_notice(agent, Notice(marked(), payload={"id": "d1"}))
        return "tool" if n == 1 else "final"

    _result, payloads = run_turn(agent, script)
    assert "the helper finished" not in str(payloads)
    assert [n.payload for n in close_turn(agent)] == [{"id": "d1"}]  # not lost: the owner delivers it


def test_real_loop_next_turn_keeps_the_notice_row_and_the_users_row_apart_in_the_live_list():
    """The turn before ended on the notice row. The next turn runs the real loop over that history: the live
    message list (what compaction reads) must hold the person's words in their own row, not under the notice."""
    from agent.conversation_compression import _is_real_user_message
    from agent.conversation_compression_scaffolding import is_user_role_scaffolding
    from tests.agent.test_run_agent import _mock_response
    wanted = "yes go ahead and delete the old branch"
    history = [{"role": "user", "content": "start"},
               {"role": "assistant", "content": None, "tool_calls": [{"id": "c1", "type": "function",
                "function": {"name": PROBE_TOOL, "arguments": "{}"}}]},
               {"role": "tool", "tool_call_id": "c1", "content": "ok"},
               notice_user_row(marked())]
    agent = loop_agent()
    agent._interruptible_api_call = lambda kwargs: _mock_response(content="done", finish_reason="stop")
    with (patch.object(agent, "_flush_messages_to_session_db"), patch.object(agent, "_persist_session"),
          patch.object(agent, "_save_trajectory"), patch.object(agent, "_cleanup_task_resources")):
        result = agent.run_conversation(wanted, conversation_history=history)
    live = result["messages"]
    notice_rows = [m for m in live if m["role"] == "user" and AUTOMATED_NOTICE in str(m["content"])]
    person_rows = [m for m in live if m["role"] == "user" and wanted in str(m["content"])]
    assert len(notice_rows) == 1 and len(person_rows) == 1 and notice_rows[0] is not person_rows[0]
    assert wanted not in str(notice_rows[0]["content"]) and AUTOMATED_NOTICE not in str(person_rows[0]["content"])
    assert notice_rows[0].get("display_kind") == NOTICE_DISPLAY_KIND
    assert is_user_role_scaffolding(notice_rows[0]) and not is_user_role_scaffolding(person_rows[0])
    assert _is_real_user_message(person_rows[0])
